# The countries where respondents split across two questionnaire languages, both with
# enough respondents and both with a questionnaire we hold. `foreign` names the country
# each language subgroup might be pulled towards, where WV7 contains one.
#
# These four are the cells of the *absolute* gain analysis, which asks whether switching
# the questionnaire language moves an LLM nearer the local speakers or nearer the
# homeland. Singapore and Canada are excluded from it and live in DISPLAY_ONLY_CELLS:
# their second survey language is English, so the language-switch arm of the English
# subgroup is the English arm byte for byte and its gain is identically zero. They do
# enter the difference-in-differences, which needs no such arm; see DID_CELLS.
CELLS = [
    dict(code=196, country="Cyprus",       langs=["el", "tr"], foreign={"el": 300, "tr": 792}),
    dict(code=804, country="Ukraine",      langs=["uk", "ru"], foreign={"ru": 643}),
    dict(code=398, country="Kazakhstan",   langs=["kk", "ru"], foreign={"ru": 643}),
    dict(code=417, country="Kyrgyzstan",   langs=["ky", "ru"], foreign={"ru": 643}),
]

# The other WV7 countries whose respondents split across two questionnaire languages with
# at least MIN_CELL_N respondents each. In both, one of the two languages is English, so
# the contrast is English against another language rather than one non-English language
# against another. That is enough for the difference-in-differences, which they enter via
# DID_CELLS, but not for the absolute gain analysis above. We hold a questionnaire in all
# four of their languages, French included.
DISPLAY_ONLY_CELLS = [
    dict(code=702, country="Singapore", langs=["en", "zh"], foreign={"en": 840, "zh": 156}),
    dict(code=124, country="Canada",    langs=["en", "fr"], foreign={"en": 840}),
]

# Cells the difference-in-differences is computed for. Eq. (4) only needs the two arms to
# name the same country and differ in the questionnaire language, which holds for the
# English-paired countries too, so they are included here. They stay out of CELLS because
# the *absolute* gain analysis is degenerate for them: the English arm of an English
# subgroup is the English prompt byte for byte, so its gain is identically zero.
# Appended last so the shared bootstrap RNG stream of the four CELLS is unchanged.
DID_CELLS = CELLS + DISPLAY_ONLY_CELLS

