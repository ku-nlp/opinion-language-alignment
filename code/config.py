def result_file(model):
    """The per-prompt model answers of one LLM. The runners write results/<model>/raw.csv,
    which carries the model's free-text output; the repository distributes parsed.csv, the
    same rows without that column. Everything downstream only needs the parsed answer."""
    raw = f"{RESULT_DIR}/{model}/raw.csv"
    return raw if os.path.exists(raw) else f"{RESULT_DIR}/{model}/parsed.csv"

