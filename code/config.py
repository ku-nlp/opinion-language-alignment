"""Shared configuration.

Design: within a multi-language country the respondents split by the language of the
questionnaire they answered, and those subgroups hold different opinions. The scoring
unit is therefore the (country, interview-language) cell, and the test that matters is a
difference-in-differences *inside one country*, where "how alignable is this country"
cancels:

    [A(steer in L1, cell c/L1) - A(steer in L1, cell c/L2)]
  - [A(steer in L2, cell c/L1) - A(steer in L2, cell c/L2)]   > 0 ?
"""
